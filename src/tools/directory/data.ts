const user = (
  id: string,
  name: string,
  department: string,
  title: string,
  groups: string[],
  extra: Partial<User> = {},
): User => {
  const [first, ...rest] = name.toLowerCase().split(' ')
  return {
    id,
    name,
    username: `${first}.${rest[rest.length - 1]}`,
    department,
    title,
    status: 'active',
    locked: false,
    mfa: true,
    mustChangePassword: false,
    groups: ['g-all', ...groups],
    lastSignIn: '2026-03-30 17:42',
    failedSignIns: 0,
    signInLocation: '',
    ...extra,
  }
}

